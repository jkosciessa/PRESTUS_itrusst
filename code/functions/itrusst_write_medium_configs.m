function config_files = itrusst_write_medium_configs(pn, setup_names)
% Write config_medium_<setup>.yaml for the literature setups and bounds from the CSVs.
%
% data/tissue_parameters.csv (+ data/tissue_setups.csv) is the single source
% of the brain/skull/water properties; the yamls are regenerated from it
% (see itrusst_tissue_properties.m) and should not be edited by hand.
%
% Inputs:
%   pn          - path struct from setup_itrusst_paths (uses pn.data, pn.configs)
%   setup_names - (optional) default {'setup1', 'reference', 'setup2', 'bottom', 'top'}
%                 (bottom/top: all brain/skull properties at one bound)
% Output:
%   config_files - cell array of written file paths

if nargin < 2
    setup_names = {'setup1', 'reference', 'setup2', 'bottom', 'top'};
end

% fields written per tissue (water: no perfusion/absorption, as in the tool configs)
fields.water = {'sound_speed', 'density', 'alpha_coeff', 'alpha_power', ...
                'thermal_conductivity', 'specific_heat_capacity'};
fields.brain = [fields.water, {'perfusion', 'absorption_fraction'}];
fields.skull = fields.brain;
tissue_labels = {'water', 'brain', 'skull'};

config_files = cell(1, numel(setup_names));
for s = 1:numel(setup_names)
    medium = itrusst_tissue_properties(setup_names{s}, pn.data);

    config_files{s} = fullfile(pn.configs, ['config_medium_' setup_names{s} '.yaml']);
    fid = fopen(config_files{s}, 'w');
    fprintf(fid, '# GENERATED by code/functions/itrusst_write_medium_configs.m from\n');
    fprintf(fid, '# data/tissue_parameters.csv / tissue_setups.csv (setup: %s) - do not edit.\n\n', setup_names{s});
    fprintf(fid, 'simulation:\n  medium: phantom\n\n');
    fprintf(fid, 'grid:\n  resolution_mm: 0.5\n  default_dims: [140, 240]\n  pml_size: 40\n  axisymmetric: 1\n  use_kWaveArray: 1\n\n');
    fprintf(fid, 'medium_properties:\n');
    for t = 1:numel(tissue_labels)
        tissue = tissue_labels{t};
        fprintf(fid, '  %s:\n', tissue);
        for f = 1:numel(fields.(tissue))
            fprintf(fid, '    %s: %s\n', fields.(tissue){f}, num2str(medium.(tissue).(fields.(tissue){f}), 6));
        end
    end
    fclose(fid);
end
