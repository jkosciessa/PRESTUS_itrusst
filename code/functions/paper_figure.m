function h = paper_figure(size_cm)
% New figure of size_cm = [width height] (cm) with the paper defaults.

S = paper_style();
h = figure('Color', 'w', 'Units', 'centimeters', 'Position', [2 2 size_cm], ...
    'Renderer', 'painters', 'InvertHardcopy', 'off');
set(h, 'DefaultAxesFontName', S.font, 'DefaultAxesFontSize', S.fontsize, ...
    'DefaultTextFontName', S.font, 'DefaultTextFontSize', S.fontsize, ...
    'DefaultAxesLineWidth', 0.5, 'DefaultAxesTickDir', 'out', ...
    'DefaultAxesTickLength', [0.02 0.02], 'DefaultAxesBox', 'off', ...
    'DefaultAxesXColor', [0.15 0.15 0.15], 'DefaultAxesYColor', [0.15 0.15 0.15], ...
    'DefaultAxesLabelFontSizeMultiplier', 1, 'DefaultAxesTitleFontSizeMultiplier', 1, ...
    'DefaultAxesTitleFontWeight', 'normal');
end
